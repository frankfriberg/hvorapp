// Turns an arena SVG exported from the design tool into `shared/arenas/<name>.ts`.
//
//   npm run arena:build -- salen
//
// The source SVG stays the source: re-export it, then re-run this. Shapes are
// classified by how the export draws them — stroked paths are outlines, the
// row colour is a row, any other fill is a marker. An outline whose id starts
// with `stage` or `stair` is that part of the stage: stairs lowest step first, numbered down from
// `stair-1` next to the stage. One with the id `tiers` is the edges of the
// stepped floor the seats stand on, and one with `tall-tiers` those whose
// long edges stand twice as tall.
//
// Beside it, `<name>_3d-raw.svg` holds the levels the 3D map is built from
// (`parseLevels`); it becomes `shared/arenas/<name>-levels.ts`.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROW_FILL = "#7299d6";

export function parseArena(svg) {
  const viewBox = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
  if (!viewBox) throw new Error('SVG has no `viewBox="0 0 w h"`');

  const shapes = [...svg.matchAll(/<path\b([^>]*)\/?>/g)].map(([, attrs]) => {
    const d = attrs.match(/\bd="([^"]+)"/)?.[1];
    if (!d) throw new Error(`path without d: ${attrs.slice(0, 80)}`);
    const fill = attrs.match(/\bfill="([^"]+)"/)?.[1];
    const stroke = attrs.match(/\bstroke="([^"]+)"/)?.[1];
    const part = attrs.match(/\bid="(stage|stair|tall-tiers|tiers)/)?.[1];

    if (stroke)
      return part ? { kind: "outline", d, part } : { kind: "outline", d };
    if (fill?.toLowerCase() === ROW_FILL) return { kind: "row", d };
    if (fill) return { kind: "marker", d };
    throw new Error(`path with neither fill nor stroke: ${d.slice(0, 40)}`);
  });

  return {
    width: Number(viewBox[1]),
    height: Number(viewBox[2]),
    shapes,
  };
}

export function arenaModule(arena) {
  return `// Generated by \`npm run arena:build\` from public/arena/*.svg — do not edit.
import type { Arena } from "../arena";

const arena: Arena = ${JSON.stringify(arena, null, 2)};

export default arena;
`;
}

// How high each level's number stands, in arena units: `stairN` and `stageN`
// are N rises up, the same for both, and `sounddeckN` a box this tall on
// `stairN`.
const RISE = 9;
const DECK_HEIGHT = 6;
// The groups the seats and the columns are drawn in.
const SEATS_GROUP = "Overlay";
const COLUMNS_GROUP = "Columns";
// Points along each curve: they only round off corners.
const CURVE_STEPS = 4;

/**
 * Reads an arena's levels, drawn in 3D: `<name>_3d-raw.svg`, exported from
 * the design tool with its layer names as ids. A level is a closed shape
 * named `stairN`, `stageN` or `sounddeckN`; where levels overlap, the higher
 * one is there, so each can run under the ones above it. Every shape in the
 * `Overlay` group is a seat, and every one in `Columns` a column. Anything
 * else is left out.
 */
export function parseLevels(svg) {
  const viewBox = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
  if (!viewBox) throw new Error('SVG has no `viewBox="0 0 w h"`');

  const levels = [];
  const seats = [];
  const columns = [];
  const groups = [];
  for (const [, end, tag, attrs, empty] of svg.matchAll(
    /<(\/?)(g|path|rect)\b([^>]*?)(\/?)>/g,
  )) {
    const id = attrs.match(/\bid="([^"]*)"/)?.[1] ?? "";
    if (tag === "g") {
      if (end) groups.pop();
      else if (!empty) groups.push(id);
      continue;
    }
    if (groups.includes(SEATS_GROUP)) {
      seats.push(...seatOf(shapeRings(tag, attrs)));
      continue;
    }
    if (groups.includes(COLUMNS_GROUP)) {
      for (const ring of shapeRings(tag, attrs)) {
        columns.push(ring.flat().map(round));
      }
      continue;
    }
    const level = id.match(/^(stair|stage|sounddeck)(\d+(?:\.\d+)?)(?:_\d+)?$/);
    if (!level) continue;
    const [, name, n] = level;
    const part = name === "sounddeck" ? "deck" : name;
    const height = {
      stair: RISE * Number(n),
      stage: RISE * Number(n),
      deck: RISE * Number(n) + DECK_HEIGHT,
    }[part];
    for (const ring of shapeRings(tag, attrs)) {
      levels.push({ part, height, ring: ring.flat().map(round) });
    }
  }
  // Highest first: the first a point is in is the one it stands on.
  levels.sort((a, b) => b.height - a.height);

  return {
    width: Number(viewBox[1]),
    height: Number(viewBox[2]),
    levels,
    seats,
    columns,
  };
}

export function levelsModule(levels) {
  // A level or a column to a line.
  const lines = (items) =>
    items.map((item) => JSON.stringify(item)).join(",\n    ");
  const seats = [];
  for (let i = 0; i < levels.seats.length; i += 5) {
    seats.push(levels.seats.slice(i, i + 5));
  }
  return `// Generated by \`npm run arena:build\` from public/arena/*_3d-raw.svg — do not edit.
import type { ArenaLevels } from "../arena";

const levels: ArenaLevels = {
  width: ${levels.width},
  height: ${levels.height},
  levels: [
    ${lines(levels.levels)},
  ],
  seats: [
    ${seats.map((seat) => seat.join(", ")).join(",\n    ")},
  ],
  columns: [
    ${lines(levels.columns)},
  ],
};

export default levels;
`;
}

const round = (value) => Math.round(value * 10) / 10;

/** A path's or rect's closed outlines, as [x, y] points, transformed. */
function shapeRings(tag, attrs) {
  const get = (name) => attrs.match(new RegExp(`\\b${name}="([^"]*)"`))?.[1];
  let rings;
  if (tag === "rect") {
    const [x, y, w, h] = ["x", "y", "width", "height"].map((name) =>
      Number(get(name) ?? 0),
    );
    rings = [
      [
        [x, y],
        [x + w, y],
        [x + w, y + h],
        [x, y + h],
      ],
    ];
  } else rings = pathRings(get("d") ?? "");
  const transform = get("transform");
  if (!transform) return rings;
  const [a, b, c, d, e, f] = parseTransform(transform);
  return rings.map((ring) =>
    ring.map(([x, y]) => [a * x + c * y + e, b * x + d * y + f]),
  );
}

/** An SVG transform list as the matrix [a, b, c, d, e, f]. */
function parseTransform(transform) {
  let m = [1, 0, 0, 1, 0, 0];
  const times = ([a, b, c, d, e, f]) => {
    m = [
      m[0] * a + m[2] * b,
      m[1] * a + m[3] * b,
      m[0] * c + m[2] * d,
      m[1] * c + m[3] * d,
      m[0] * e + m[2] * f + m[4],
      m[1] * e + m[3] * f + m[5],
    ];
  };
  for (const [, name, args] of transform.matchAll(/(\w+)\(([^)]*)\)/g)) {
    const n = args
      .split(/[\s,]+/)
      .filter(Boolean)
      .map(Number);
    if (name === "matrix") times(n);
    else if (name === "translate") times([1, 0, 0, 1, n[0], n[1] ?? 0]);
    else if (name === "scale") times([n[0], 0, 0, n[1] ?? n[0], 0, 0]);
    else if (name === "rotate") {
      const r = (n[0] * Math.PI) / 180;
      const [cx, cy] = [n[1] ?? 0, n[2] ?? 0];
      times([1, 0, 0, 1, cx, cy]);
      times([Math.cos(r), Math.sin(r), -Math.sin(r), Math.cos(r), 0, 0]);
      times([1, 0, 0, 1, -cx, -cy]);
    } else throw new Error(`unsupported transform: ${name}`);
  }
  return m;
}

/**
 * The closed outlines of path data, curves sampled. Reads M, L, H, V, C, S
 * and Z, absolute or relative.
 */
function pathRings(d) {
  const tokens = d.match(/[a-zA-Z]|-?(?:\d*\.\d+|\d+)(?:e-?\d+)?/g) ?? [];
  const rings = [];
  let ring = [];
  let i = 0;
  let command = "M";
  let [x, y, startX, startY] = [0, 0, 0, 0];
  // The last curve's second control point, which a smooth curve mirrors.
  let control = null;
  const next = () => Number(tokens[i++]);
  const close = () => {
    if (ring.length > 2) rings.push(ring);
    ring = [];
  };
  while (i < tokens.length) {
    if (/[a-zA-Z]/.test(tokens[i])) command = tokens[i++];
    const relative = command === command.toLowerCase();
    const dx = relative ? x : 0;
    const dy = relative ? y : 0;
    const after = control;
    control = null;
    switch (command.toLowerCase()) {
      case "m":
        close();
        x = next() + dx;
        y = next() + dy;
        [startX, startY] = [x, y];
        ring.push([x, y]);
        command = relative ? "l" : "L";
        break;
      case "l":
        x = next() + dx;
        y = next() + dy;
        ring.push([x, y]);
        break;
      case "h":
        x = next() + dx;
        ring.push([x, y]);
        break;
      case "v":
        y = next() + dy;
        ring.push([x, y]);
        break;
      case "c":
      case "s": {
        const [x1, y1] =
          command.toLowerCase() === "s"
            ? after
              ? [2 * x - after[0], 2 * y - after[1]]
              : [x, y]
            : [next() + dx, next() + dy];
        const [x2, y2] = [next() + dx, next() + dy];
        const [x3, y3] = [next() + dx, next() + dy];
        for (let s = 1; s <= CURVE_STEPS; s++) {
          const t = s / CURVE_STEPS;
          const u = 1 - t;
          ring.push([
            u ** 3 * x + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t ** 3 * x3,
            u ** 3 * y + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t ** 3 * y3,
          ]);
        }
        [x, y] = [x3, y3];
        control = [x2, y2];
        break;
      }
      case "z":
        close();
        [x, y] = [startX, startY];
        break;
      default:
        throw new Error(`unsupported path command: ${command}`);
    }
  }
  close();
  // Without the point that closes it, nor any repeated one.
  return rings.map((points) =>
    points.filter(([px, py], j) => {
      const [qx, qy] = points[(j + 1) % points.length];
      return Math.hypot(qx - px, qy - py) > 1e-3;
    }),
  );
}

/**
 * A seat as its centre, width, height and turn in degrees: the box round
 * its outline, turned to its longest side.
 */
function seatOf(rings) {
  const points = rings.flat();
  if (points.length === 0) return [];
  let [angle, longest] = [0, 0];
  for (const ring of rings) {
    ring.forEach(([x1, y1], j) => {
      const [x2, y2] = ring[(j + 1) % ring.length];
      const length = Math.hypot(x2 - x1, y2 - y1);
      if (length > longest)
        [angle, longest] = [Math.atan2(y2 - y1, x2 - x1), length];
    });
  }
  // Within a quarter turn either way: a box turned a half is the same box.
  angle =
    ((((angle + Math.PI / 4) % (Math.PI / 2)) + Math.PI / 2) % (Math.PI / 2)) -
    Math.PI / 4;
  const [cos, sin] = [Math.cos(angle), Math.sin(angle)];
  const along = points.map(([x, y]) => x * cos + y * sin);
  const across = points.map(([x, y]) => -x * sin + y * cos);
  const [u0, u1] = [Math.min(...along), Math.max(...along)];
  const [v0, v1] = [Math.min(...across), Math.max(...across)];
  const [u, v] = [(u0 + u1) / 2, (v0 + v1) / 2];
  return [
    round(u * cos - v * sin),
    round(u * sin + v * cos),
    round(u1 - u0),
    round(v1 - v0),
    Math.round(((angle * 180) / Math.PI) * 100) / 100,
  ];
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const name = process.argv[2];
  if (!name) throw new Error("usage: npm run arena:build -- <arena>");

  const root = join(import.meta.dirname, "..");
  const svg = readFileSync(join(root, "public/arena", `${name}.svg`), "utf8");
  const out = join(root, "shared/arenas", `${name}.ts`);
  const arena = parseArena(svg);

  writeFileSync(out, arenaModule(arena));
  console.log(`${out}: ${arena.shapes.length} shapes`);

  const raw = join(root, "public/arena", `${name}_3d-raw.svg`);
  if (existsSync(raw)) {
    const levelsOut = join(root, "shared/arenas", `${name}-levels.ts`);
    const levels = parseLevels(readFileSync(raw, "utf8"));
    writeFileSync(levelsOut, levelsModule(levels));
    console.log(
      `${levelsOut}: ${levels.levels.length} levels, ${levels.seats.length / 5} seats`,
    );
  }
}
