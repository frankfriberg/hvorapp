// Turns an arena SVG exported from the design tool into `shared/arenas/<name>.ts`.
//
//   npm run arena:build -- salen
//
// The source SVG stays the source: re-export it, then re-run this. Shapes are
// classified by how the export draws them — stroked paths are outlines, the
// row colour is a row, any other fill is a marker.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROW_FILL = "#7299d6";

export function parseArena(svg) {
  const viewBox = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
  if (!viewBox) throw new Error('SVG has no `viewBox="0 0 w h"`');

  const shapes = [...svg.matchAll(/<path\b([^>]*)\/?>/g)].map(([, attrs]) => {
    const d = attrs.match(/\bd="([^"]+)"/)?.[1];
    if (!d) throw new Error(`path without d: ${attrs.slice(0, 80)}`);
    const fill = attrs.match(/\bfill="([^"]+)"/)?.[1];
    const stroke = attrs.match(/\bstroke="([^"]+)"/)?.[1];

    if (stroke) return { kind: "outline", d };
    if (fill?.toLowerCase() === ROW_FILL) return { kind: "row", d };
    if (fill) return { kind: "marker", d };
    throw new Error(`path with neither fill nor stroke: ${d.slice(0, 40)}`);
  });

  return {
    width: Number(viewBox[1]),
    height: Number(viewBox[2]),
    shapes,
  };
}

export function arenaModule(arena) {
  return `// Generated by \`npm run arena:build\` from public/arena/*.svg — do not edit.
import type { Arena } from "../arena";

const arena: Arena = ${JSON.stringify(arena, null, 2)};

export default arena;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const name = process.argv[2];
  if (!name) throw new Error("usage: npm run arena:build -- <arena>");

  const root = join(import.meta.dirname, "..");
  const svg = readFileSync(join(root, "public/arena", `${name}.svg`), "utf8");
  const out = join(root, "shared/arenas", `${name}.ts`);
  const arena = parseArena(svg);

  writeFileSync(out, arenaModule(arena));
  console.log(`${out}: ${arena.shapes.length} shapes`);
}
